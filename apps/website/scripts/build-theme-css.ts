import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { gukTheme, primitiveTokens } from "../src/theme/tokens";

const declarationBlock = (tokens: Record<string, string>, prefix: string) =>
  Object.entries(tokens)
    .map(([token, value]) => `  --gk-${prefix}${token}: ${value};`)
    .join("\n");

const css = `/* Generated by scripts/build-theme-css.ts. Do not edit manually. */
:root {
${declarationBlock(primitiveTokens, "color-")}
${declarationBlock(gukTheme, "")}
}
`;

await writeFile(
  fileURLToPath(new URL("../src/theme/tokens.css", import.meta.url)),
  css,
);
